export function findLesson(trackId: string, lessonId: string) {
  const track = tracks.find((t) => t.id === trackId);
  const lesson = track?.lessons.find((l) => l.id === lessonId);
  return track && lesson ? { track, lesson } : null;
}

export function referenceFiles(lesson: Lesson) {
  const files: Record<string, string> = {};
  for (const s of lesson.steps) {
    if (s.kind === "file") files[s.path] ??= "";
    if (s.kind === "type") files[s.path] = (files[s.path] ? files[s.path] + "\n" : "") + s.lines.map((l) => l.code).join("\n");
  }
  return files;
}

export function referenceFolders(lesson: Lesson) {
  return lesson.steps.filter((s) => s.kind === "folder").map((s) => s.path);
}

export const allLessons = tracks.flatMap((t) => t.lessons.map((l) => ({ track: t, lesson: l })));
